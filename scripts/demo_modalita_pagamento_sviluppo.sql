-- SOLO SVILUPPO: 12 ordini dimostrativi e 7 fatture acconto (6 numerate, 1 non validata).
-- Non sovrascrive dati esistenti. Nessun movimento o saldo di magazzino.
SET NOCOUNT ON;
SET XACT_ABORT ON;
DECLARE @ConfermaAmbienteSviluppo bit=0;
IF @ConfermaAmbienteSviluppo<>1 THROW 51000,'Confermare esplicitamente il DB di sviluppo.',1;
DECLARE @Anno int=YEAR(GETDATE()), @Oggi date=CONVERT(date,GETDATE());
DECLARE @ProssimoMese date=DATEADD(month,1,DATEFROMPARTS(@Anno,MONTH(@Oggi),1));
DECLARE @MesePrecedente date=DATEADD(month,-1,DATEFROMPARTS(@Anno,MONTH(@Oggi),1));
DECLARE @Gennaio date=DATEFROMPARTS(@Anno+1,1,1);
DECLARE @Casi TABLE (Numero int PRIMARY KEY,Serie varchar(3),Stato varchar(30),Scenario varchar(100),Fatturato decimal(18,2));
INSERT @Casi VALUES
(910101,'01','INCOMPLETO','01 - Acconto immediato 30%, saldo al pronto',0),
(910102,'01','INCOMPLETO','02 - Acconto nel mese prossimo',0),
(910103,'01','INCOMPLETO','03 - Acconto gennaio anno prossimo',0),
(910104,'01','INCOMPLETO','04 - Tre acconti senza cambio data: anomalie',0),
(910105,'11','INCOMPLETO','05 - Quattro tranche 25%, fatturato 35%',350),
(910106,'11','INCOMPLETO','06 - Quattro tranche 25%, fatturato 60%',600),
(910107,'11','COMPLETO','07 - Quattro tranche 25%, fatturato 100%',1000),
(910108,'11','COMPLETO','08 - Acconto fatto 30%, saldo al pronto dovuto',300),
(910109,'01','INCOMPLETO','09 - Acconto fatto 30%, saldo attende completo',300),
(910110,'01','INCOMPLETO','10 - Due acconti con date distinte corrette',0),
(910111,'11','COMPLETO','11 - Acconto fatto 100%, saldo zero',1000),
(910112,'11','INCOMPLETO','12 - Acconto fatto, saldo con data futura',300);
BEGIN TRANSACTION;
IF EXISTS(SELECT 1 FROM PIANOCONTI WITH(UPDLOCK,HOLDLOCK) WHERE GRUPPOCONTO=1231 AND SOTTOCONTO='990901')
 THROW 51001,'Cliente dimostrativo gia presente: nessuna sovrascrittura.',1;
IF EXISTS(SELECT 1 FROM ORDCLI o WITH(UPDLOCK,HOLDLOCK) JOIN @Casi c ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero)
 OR EXISTS(SELECT 1 FROM ORDCLI2 o JOIN @Casi c ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero)
 OR EXISTS(SELECT 1 FROM GO_ORDINE o JOIN @Casi c ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero)
 OR EXISTS(SELECT 1 FROM GO_ORDINE_DETTAGLIO o JOIN @Casi c ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero)
 OR EXISTS(SELECT 1 FROM GO_PAGAMENTO_ORDINE o JOIN @Casi c ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero)
 THROW 51002,'Riferimenti ordine occupati: nessun dato modificato.',1;
IF EXISTS(SELECT 1 FROM FATTURE f JOIN @Casi c ON f.ANNO=@Anno AND f.SERIE='A' AND f.PROGRESSIVO=c.Numero)
 OR EXISTS(SELECT 1 FROM FATTURE2 f JOIN @Casi c ON f.ANNO=@Anno AND f.SERIE='A' AND f.PROGRESSIVO=c.Numero)
 THROW 51003,'Riferimenti fatture occupati: nessun dato modificato.',1;
IF NOT EXISTS(SELECT 1 FROM ORDCLI WHERE SERIE='01') OR NOT EXISTS(SELECT 1 FROM ORDCLI WHERE SERIE='11')
 THROW 51004,'Serie dimostrative non presenti nel flusso reale.',1;
DECLARE @Articolo varchar(13),@Unita varchar(3),@Iva varchar(3),@Magazzino varchar(3);
SELECT TOP 1 @Articolo=d.FARTICOLO,@Unita=d.FUNITAMISURA,@Iva=d.FCODICEIVA,@Magazzino=d.MAGAZZ
FROM ORDCLI2 d JOIN ARTICOLI_TAB a ON a.ARTICOLO=d.FARTICOLO
WHERE d.TIPORIGO=' ' AND d.FARTICOLO NOT LIKE '*%' AND d.QUANTITA>0;
IF @Articolo IS NULL THROW 51005,'Articolo reale di riferimento mancante.',1;
DECLARE @Pagamento varchar(3)=(SELECT TOP 1 FCODICEPAGAMENT FROM ORDCLI WHERE SERIE='01' ORDER BY ANNO DESC,PROGRESSIVO DESC);
INSERT PIANOCONTI (GRUPPOCONTO,SOTTOCONTO,INTESTAZIONE,CLIFOR,STATORESIDENZA,STATOESTERO,
 INDIRIZZO,LOCALITA,CAP,PROVINCIA,TELEFONO,CELLULARE,EMAIL,PEC,LATITUDINE,LONGITUDINE,DCODICEPAGAMENT)
SELECT TOP 1 1231,'990901','TEST MODALITA PAGAMENTO',CLIFOR,STATORESIDENZA,STATOESTERO,
 'DATI DIMOSTRATIVI','TEST','','','','','','',0,0,@Pagamento
FROM PIANOCONTI WHERE GRUPPOCONTO=1231 ORDER BY SOTTOCONTO;
IF @@ROWCOUNT<>1 THROW 51006,'Anagrafica cliente di riferimento non trovata.',1;
INSERT ORDCLI (ANNO,SERIE,PROGRESSIVO,GRUPPOCLIENTE,CONTOCLIENTE,GRUPPOFATTURA,CONTOFATTURA,
 PROVVISORIO,DATAORDINE,DATACONFERMA,NUMEROCONFERMA,FCODICEPAGAMENT,RIFERIMENTO,SYS_CREATEDATE,SYS_UPDATEDATE)
SELECT @Anno,Serie,Numero,1231,'990901',1231,'990901',' ',@Oggi,@Oggi,
 CONVERT(varchar(12),Numero),@Pagamento,'TEST PAGAMENTI '+Scenario,GETDATE(),GETDATE() FROM @Casi;
INSERT GO_ORDINE (ANNO,SERIE,PROGRESSIVO,STATUS,WARN_NO_BOLLA,LOCKED,HAS_FIRMA,HAS_PRONTO_CONSEGNA,HAS_CARICO,NOTE)
SELECT @Anno,Serie,Numero,Stato,'F','F','F',CASE WHEN Stato='COMPLETO' THEN 'T' ELSE 'F' END,'F',
 'TEST PAGAMENTI '+Scenario FROM @Casi;

DECLARE @Righe TABLE (Numero int,Rigo int,Codice varchar(13),Percentuale int,DataPrevista date);
INSERT @Righe
SELECT c.Numero,2,'*ACCONTO',CASE WHEN c.Numero=910110 THEN 20 WHEN c.Numero=910111 THEN 100 ELSE 30 END,
 CASE WHEN c.Numero=910102 THEN @ProssimoMese WHEN c.Numero=910103 THEN @Gennaio
      WHEN c.Numero=910110 THEN @MesePrecedente ELSE @Oggi END
FROM @Casi c WHERE c.Numero NOT BETWEEN 910104 AND 910107;
INSERT @Righe SELECT Numero,r.Rigo,'*ACCONTO',25,@Oggi FROM @Casi CROSS JOIN (VALUES(2),(3),(4)) r(Rigo)
 WHERE Numero BETWEEN 910104 AND 910107;
INSERT @Righe VALUES(910110,3,'*ACCONTO',30,@ProssimoMese);
INSERT @Righe
SELECT Numero,CASE WHEN Numero BETWEEN 910104 AND 910107 THEN 5 WHEN Numero=910110 THEN 4 ELSE 3 END,'*SALDO',
 CASE WHEN Numero BETWEEN 910104 AND 910107 THEN 25 WHEN Numero=910110 THEN 50 WHEN Numero=910111 THEN 0 ELSE 70 END,
 CASE WHEN Numero=910112 THEN DATEADD(day,14,@ProssimoMese) ELSE @Oggi END FROM @Casi;

DECLARE @Base int=(SELECT ISNULL(MAX(PROGRGENERALE),0) FROM ORDCLI2 WITH(UPDLOCK,HOLDLOCK));
SELECT @Base=CASE WHEN ISNULL(MAX(PROGRGENERALE),0)>@Base THEN MAX(PROGRGENERALE) ELSE @Base END FROM GO_ORDINE_DETTAGLIO;
SELECT @Base=CASE WHEN ISNULL(MAX(PROGRGENERALE),0)>@Base THEN MAX(PROGRGENERALE) ELSE @Base END FROM GO_PAGAMENTO_ORDINE;
INSERT ORDCLI2 (ANNO,SERIE,PROGRESSIVO,RIGO,PROGRGENERALE,TIPORIGO,FARTICOLO,FDESCRARTICOLO,
 DATACONFCONSEGNA,DATARICHCONSEGNA,QUANTITA,QUANTITAV,QUANTITA2,PREZZO,FUNITAMISURA,FCOEFFICIENTE,
 COEFPREZZO,SCONTOARTICOLO,SCONTOC1,SCONTOC2,SCONTOP,MAGAZZ,FCODICEIVA,SALDOACCONTO,
 DATAMODIFICA,USERNAME,SYS_CREATEDATE,SYS_CREATEUSER,SYS_UPDATEDATE,SYS_UPDATEUSER,PID_ORDCLI)
SELECT @Anno,c.Serie,c.Numero,x.Rigo,@Base+ROW_NUMBER() OVER(ORDER BY c.Numero,x.Rigo),
 CASE WHEN x.Rigo=1 THEN ' ' ELSE 'C' END,CASE WHEN x.Rigo=1 THEN @Articolo ELSE x.Codice END,
 CASE WHEN x.Rigo=1 THEN 'TEST PAGAMENTI - materiale dimostrativo' WHEN x.Codice='*ACCONTO' THEN 'TEST ACCONTO' ELSE 'TEST SALDO' END,
 x.DataPrevista,x.DataPrevista,CASE WHEN x.Rigo=1 THEN 1 ELSE x.Percentuale END,
 CASE WHEN x.Rigo=1 THEN 1 ELSE 0 END,CASE WHEN x.Rigo=1 THEN 1 ELSE 0 END,
 CASE WHEN x.Rigo=1 THEN 1000 ELSE 0 END,@Unita,1,1,0,0,0,0,@Magazzino,@Iva,'',
 @Oggi,'TEST_PAG',GETDATE(),'TEST_PAG',GETDATE(),'TEST_PAG',o.ID_ORDCLI
FROM @Casi c JOIN ORDCLI o ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero
CROSS APPLY (SELECT 1 Rigo,CAST(NULL AS varchar(13)) Codice,1 Percentuale,@Oggi DataPrevista
 UNION ALL SELECT Rigo,Codice,Percentuale,DataPrevista FROM @Righe r WHERE r.Numero=c.Numero) x;

INSERT GO_ORDINE_DETTAGLIO (ANNO,SERIE,PROGRESSIVO,RIGO,PROGRGENERALE,QUANTITA_DA_CONSEGNARE,
 QTA_CONS_NO_BOLLA,FLAG_RISERVATO,FLAG_NON_DISPONIBILE,FLAG_ORDINATO,FLAG_CONSEGNATO,FLAG_PRONTO_CONSEGNA,
 HAS_BOLLA,STATUS,QTA_RISERVATA,QTA_PRONTO_CONSEGNA)
SELECT d.ANNO,d.SERIE,d.PROGRESSIVO,d.RIGO,d.PROGRGENERALE,1,0,
 CASE WHEN c.Stato='COMPLETO' THEN 'T' ELSE 'F' END,'F',
 CASE WHEN c.Stato='INCOMPLETO' THEN 'T' ELSE 'F' END,'F',
 CASE WHEN c.Stato='COMPLETO' THEN 'T' ELSE 'F' END,'F',c.Stato,
 CASE WHEN c.Stato='COMPLETO' THEN 1 ELSE 0 END,CASE WHEN c.Stato='COMPLETO' THEN 1 ELSE 0 END
FROM ORDCLI2 d JOIN @Casi c ON d.ANNO=@Anno AND d.SERIE=c.Serie AND d.PROGRESSIVO=c.Numero WHERE d.RIGO=1;

INSERT FATTURE (ANNO,SERIE,PROGRESSIVO,GRUPPOCLIENTE,CONTOCLIENTE,GRUPPOFATTURA,CONTOFATTURA,
 DATABOLLA,NUMEROBOLLA,NUMEROFATTURA,DATAFATTURA,TIPOFATTURA,SYS_CREATEDATE,SYS_UPDATEDATE)
SELECT @Anno,'A',Numero,1231,'990901',1231,'990901',@Oggi,CONVERT(varchar(12),Numero),
 CASE WHEN Numero=910112 THEN NULL ELSE CONVERT(varchar(12),Numero) END,
 CASE WHEN Numero=910112 THEN NULL ELSE @Oggi END,'A',GETDATE(),GETDATE()
FROM @Casi WHERE Fatturato>0;
DECLARE @BaseFatture int=(SELECT ISNULL(MAX(PROGRGENERALE),0) FROM FATTURE2 WITH(UPDLOCK,HOLDLOCK));
INSERT FATTURE2 (ANNO,SERIE,PROGRESSIVO,RIGO,PROGRGENERALE,TIPORIGO,FARTICOLO,FDESCRARTICOLO,
 QUANTITA,PREZZO,FCODICEIVA,PROGRORDCLI,FUNITAMISURA,MAGAZZ,SYS_CREATEDATE,SYS_CREATEUSER,SYS_UPDATEDATE,SYS_UPDATEUSER)
SELECT @Anno,'A',c.Numero,r.Rigo,@BaseFatture+ROW_NUMBER() OVER(ORDER BY c.Numero,r.Rigo),
 CASE WHEN r.Rigo=1 THEN 'V' ELSE 'C' END,CASE WHEN r.Rigo=1 THEN '*ACC' ELSE '' END,
 CASE WHEN r.Rigo=1 THEN 'TEST Acconto' WHEN r.Rigo=2 THEN 'Su prossima fornitura di materiale come da'
 ELSE 'ordine n.'+CONVERT(varchar(4),@Anno)+'/'+c.Serie+'/'+CONVERT(varchar(12),c.Numero) END,
 0,CASE WHEN r.Rigo=1 THEN c.Fatturato ELSE 0 END,
 CASE WHEN r.Rigo=1 THEN @Iva ELSE '' END,0,CASE WHEN r.Rigo=1 THEN '.' ELSE '' END,
 CASE WHEN r.Rigo=1 THEN @Magazzino ELSE '' END,GETDATE(),'TEST_PAG',GETDATE(),'TEST_PAG'
FROM @Casi c CROSS JOIN (VALUES(1),(2),(3)) r(Rigo) WHERE c.Fatturato>0;
IF (SELECT COUNT(*) FROM ORDCLI o JOIN @Casi c ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero)<>12
 THROW 51007,'Verifica numero ordini fallita.',1;
IF (SELECT COUNT(*) FROM ORDCLI2 o JOIN @Casi c ON o.ANNO=@Anno AND o.SERIE=c.Serie AND o.PROGRESSIVO=c.Numero AND o.FARTICOLO IN ('*ACCONTO','*SALDO'))<>33
 THROW 51008,'Verifica righe pagamento fallita.',1;
COMMIT;
SELECT @Anno ANNO,Serie,Numero,Scenario,Fatturato FROM @Casi ORDER BY Numero;
