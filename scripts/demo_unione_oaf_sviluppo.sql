SET NOCOUNT ON;
SET XACT_ABORT ON;
DECLARE @ConfermaAmbienteSviluppo bit = 0;
IF @ConfermaAmbienteSviluppo <> 1 THROW 51000, 'Confermare esplicitamente ambiente di sviluppo prima di eseguire.', 1;
DECLARE @Anno int = YEAR(GETDATE());
DECLARE @Ordini TABLE (Serie varchar(3), Numero int, Conto varchar(6), Scenario varchar(120));
INSERT INTO @Ordini VALUES
('B',900001,'011000','TEST UNIONE - Tubes A - stesso fornitore'),
('B',900002,'011000','TEST UNIONE - Tubes B - stesso fornitore'),
('B',900003,'010507','TEST UNIONE - Atlas - warning fornitore diverso'),
('B',900004,'010600','TEST UNIONE - Mirage - warning fornitore diverso'),
('B',900010,'011000','TEST UNIONE - destinazione Tubes - stessa serie B'),
('B',900011,'011000','TEST UNIONE - sorgente Tubes - stessa serie B'),
('B',900012,'010507','TEST UNIONE - Atlas estraneo - NON deve essere modificato');
BEGIN TRANSACTION;
IF (SELECT COUNT(*) FROM PIANOCONTI WHERE GRUPPOCONTO=2351 AND SOTTOCONTO IN ('011000','010507','010600'))<>3
 THROW 51001,'Anagrafiche dei tre fornitori non presenti o non univoche.',1;
IF EXISTS (SELECT 1 FROM @Ordini t JOIN ORDFOR o ON o.ANNOOAF=@Anno AND o.SERIEOAF=t.Serie AND o.PROGRESSIVOOAF=t.Numero)
 OR EXISTS (SELECT 1 FROM @Ordini t JOIN ORDFOR2 o ON o.ANNOOAF=@Anno AND o.SERIEOAF=t.Serie AND o.PROGRESSIVOOAF=t.Numero)
 OR EXISTS (SELECT 1 FROM @Ordini t JOIN GO_ORDFOR o ON o.ANNOOAF=@Anno AND o.SERIEOAF=t.Serie AND o.PROGRESSIVOOAF=t.Numero)
 OR EXISTS (SELECT 1 FROM @Ordini t JOIN GO_ORDFOR2 o ON o.ANNOOAF=@Anno AND o.SERIEOAF=t.Serie AND o.PROGRESSIVOOAF=t.Numero)
 OR EXISTS (SELECT 1 FROM @Ordini t JOIN GO_ORDINE_FORNITORE o ON o.ANNOOAF=@Anno AND o.SERIEOAF=t.Serie AND o.PROGRESSIVOOAF=t.Numero)
 THROW 51002,'Almeno un riferimento e gia presente: nessun dato modificato.',1;
DECLARE @BaseGenerale int=(SELECT ISNULL(MAX(PROGRGENERALE),0) FROM ORDFOR2 WITH(UPDLOCK,HOLDLOCK));
INSERT INTO ORDFOR (ANNOOAF,SERIEOAF,PROGRESSIVOOAF,GRUPPOFOAF,CONTOFOAF,DATAORDINE,PROVVISORIO,
 OOGGETTO,OGGETTO,SYS_CREATEUSER,SYS_UPDATEUSER,SYS_CREATEDATE,SYS_UPDATEDATE)
SELECT @Anno,Serie,Numero,2351,Conto,CONVERT(date,GETDATE()),'F','TEST',Scenario,
 'TEST_UNIONE','TEST_UNIONE',GETDATE(),GETDATE() FROM @Ordini;
INSERT INTO ORDFOR2 (ANNOOAF,SERIEOAF,PROGRESSIVOOAF,RIGO,PROGRGENERALE,OARTICOLO,ODESCRARTICOLO,
 OQUANTITA,OQUANTITAV,OQUANTITA2,OPREZZO,OUNITAMISURA,OCODICEIVA,TIPORIGOOAF,OSALDOACCONTO,
 FSCONTOARTICOLO,SCONTOF1,SCONTOF2,FSCONTOP,OVALORE,OCOEFFICIENTE,OMAGAZZ,PROVENIENZA,PID,NOTEORDFOR2,
 SYS_CREATEUSER,SYS_UPDATEUSER,SYS_CREATEDATE,SYS_UPDATEDATE)
SELECT @Anno,t.Serie,t.Numero,r.Rigo,@BaseGenerale+ROW_NUMBER() OVER(ORDER BY t.Serie,t.Numero,r.Rigo),
 'TST-OAF-'+CAST(r.Rigo AS varchar(1)),'TEST UNIONE '+CAST(t.Numero AS varchar(10))+' - riga '+CAST(r.Rigo AS varchar(1)),
 r.Rigo,r.Rigo,r.Rigo,100+r.Rigo,'PZ','22',' ','',0,0,0,0,r.Rigo*(100+r.Rigo),1,'B','',0,t.Scenario,
 'TEST_UNIONE','TEST_UNIONE',GETDATE(),GETDATE()
FROM @Ordini t CROSS JOIN (VALUES(1),(2)) r(Rigo);
INSERT INTO GO_ORDINE_FORNITORE (ANNOOAF,SERIEOAF,PROGRESSIVOOAF,FLINVIATO,NOTE)
SELECT @Anno,Serie,Numero,'F',Scenario FROM @Ordini;
IF (SELECT COUNT(*) FROM ORDFOR2 r JOIN @Ordini t ON r.ANNOOAF=@Anno AND r.SERIEOAF=t.Serie AND r.PROGRESSIVOOAF=t.Numero)<>14
 THROW 51003,'Numero righe inatteso: operazione annullata.',1;
COMMIT TRANSACTION;
SELECT o.ANNOOAF,o.SERIEOAF,o.PROGRESSIVOOAF,p.INTESTAZIONE,o.PROVVISORIO,
 (SELECT COUNT(*) FROM ORDFOR2 r WHERE r.ANNOOAF=o.ANNOOAF AND r.SERIEOAF=o.SERIEOAF AND r.PROGRESSIVOOAF=o.PROGRESSIVOOAF) AS RIGHE,t.Scenario
FROM @Ordini t JOIN ORDFOR o ON o.ANNOOAF=@Anno AND o.SERIEOAF=t.Serie AND o.PROGRESSIVOOAF=t.Numero
JOIN PIANOCONTI p ON p.GRUPPOCONTO=o.GRUPPOFOAF AND p.SOTTOCONTO=o.CONTOFOAF
ORDER BY o.SERIEOAF,o.PROGRESSIVOOAF;
