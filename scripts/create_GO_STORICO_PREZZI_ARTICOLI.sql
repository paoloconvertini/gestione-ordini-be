-- SQL Server: eseguire nel database aziendale della API principale PRIMA del backend aggiornato.
-- Rieseguibile. La cronologia parte dalle nuove modifiche della pagina Prezzi articoli.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID(N'dbo.GO_STORICO_PREZZI_ARTICOLI', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.GO_STORICO_PREZZI_ARTICOLI (
        ID bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_GO_STORICO_PREZZI_ARTICOLI PRIMARY KEY,
        ARTICOLO varchar(13) NOT NULL,
        DATA_MODIFICA datetime2 NOT NULL CONSTRAINT DF_GO_STORICO_PREZZI_ARTICOLI_DATA DEFAULT GETDATE(),
        PREZZO_PRECEDENTE decimal(28,8) NULL,
        PREZZO_BASE decimal(28,8) NOT NULL,
        UTENTE varchar(255) NULL
    );
    CREATE INDEX IX_GO_STORICO_PREZZI_ARTICOLI_ARTICOLO_DATA
        ON dbo.GO_STORICO_PREZZI_ARTICOLI (ARTICOLO, DATA_MODIFICA DESC, ID DESC);
END;
COMMIT;
